# Only translate whole literal text nodes. HTML attributes, JavaScript,
# comments and Django values remain untouched.
DISPLAY_NODE = re.compile(r'(?<=>)(\s*)([^<>{}]{1,180}?)(\s*)(?=<)')
IGNORED_BLOCK = re.compile(
    r'(<(?:script|style)\b[^>]*>.*?</(?:script|style)>|<!--.*?-->|{#.*?#})',
    re.IGNORECASE | re.DOTALL,
)


def translate_labels(text):
    """Translate checked static text without interpreting scan data."""
    def translate(match):
        key = ' '.join(unescape(match[2]).split()).lower()
        if key == 'info' and match[2].strip() == 'INFO':
            return match[0]
        label = LABELS.get(key)
        return match[1] + label + match[3] if label else match[0]

    parts = IGNORED_BLOCK.split(text)
    for index in range(0, len(parts), 2):
        parts[index] = DISPLAY_NODE.sub(translate, parts[index])
    return ''.join(parts)
